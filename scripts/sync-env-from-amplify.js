#!/usr/bin/env node
/**
 * Fetches env vars from the GetTrainMate Amplify app and writes apps/web/.env
 * so localhost matches Amplify (same Cognito pool + same API = no 401).
 *
 * Prerequisites: AWS CLI configured. Run: node scripts/sync-env-from-amplify.js
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const ENV_PATH = path.join(ROOT, 'apps', 'web', '.env');
const REGION = process.env.AWS_REGION || 'us-east-1';
const APP_NAME = 'GetTrainMate';

function listApps() {
  const out = execSync(
    `aws amplify list-apps --region ${REGION} --output json`,
    { encoding: 'utf8' }
  );
  const apps = JSON.parse(out).apps || [];
  const app = apps.find((a) => a.name === APP_NAME);
  if (!app) {
    console.error(`\n❌ Amplify app "${APP_NAME}" not found.\n`);
    process.exit(1);
  }
  return app;
}

function main() {
  console.log(`📡 Fetching env from Amplify app: ${APP_NAME}`);
  const app = listApps();
  const vars = app.environmentVariables || {};
  const userPoolId = vars.VITE_COGNITO_USER_POOL_ID;
  const clientId = vars.VITE_COGNITO_CLIENT_ID;
  const apiUrl = vars.VITE_API_URL || '';

  if (!userPoolId || !clientId) {
    console.error('\n❌ Amplify app missing VITE_COGNITO_USER_POOL_ID or VITE_COGNITO_CLIENT_ID.\n');
    process.exit(1);
  }

  const lines = [
    '# Auto-generated by scripts/sync-env-from-amplify.js',
    '# Matches Amplify env so localhost uses same Cognito + API (avoids 401)',
    '',
    'VITE_COGNITO_USER_POOL_ID=' + userPoolId,
    'VITE_COGNITO_CLIENT_ID=' + clientId,
    'VITE_COGNITO_REGION=' + (vars.VITE_COGNITO_REGION || REGION),
    '',
  ];
  if (apiUrl) {
    const url = apiUrl.replace(/\/+$/, '');
    lines.push('VITE_API_URL=' + url + '/');
    lines.push('');
  }
  // Amplify does not set AppSync – so we don't set it; app will use REST for /me and discover
  lines.push('# AppSync not set in Amplify – app uses REST API for /me and discover');
  if (vars.VITE_ADMIN_ALLOWLIST) {
    lines.push('VITE_ADMIN_ALLOWLIST=' + vars.VITE_ADMIN_ALLOWLIST);
  }

  fs.writeFileSync(ENV_PATH, lines.join('\n') + '\n', 'utf8');
  console.log('✅ Wrote', ENV_PATH);
  console.log('   Cognito pool:', userPoolId);
  console.log('   API URL:', apiUrl || '(none)');
  console.log('\nRestart the dev server (npm run web:dev) so Vite reloads .env.');
}

main();
