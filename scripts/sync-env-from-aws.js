#!/usr/bin/env node
/**
 * Fetches Cognito + API config from the deployed CDK stack (CloudFormation)
 * and creates apps/web/.env for local development.
 *
 * Prerequisites: AWS CLI configured (aws configure) and stack deployed.
 * Run: node scripts/sync-env-from-aws.js
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const STACK_NAME = 'GetTrainMateStack';
const REGION = process.env.AWS_REGION || process.env.CDK_DEFAULT_REGION || 'us-east-1';

function getStackOutputs() {
  try {
    const out = execSync(
      `aws cloudformation describe-stacks --stack-name ${STACK_NAME} --region ${REGION} --query 'Stacks[0].Outputs' --output json`,
      { encoding: 'utf8' }
    );
    return JSON.parse(out);
  } catch (e) {
    if (e.message && e.message.includes('does not exist')) {
      console.error(`\n❌ Stack "${STACK_NAME}" not found. Deploy first: npm run infra:deploy\n`);
    } else {
      console.error('\n❌ AWS CLI error. Ensure AWS CLI is configured (aws configure) and you have access.\n', e.message);
    }
    process.exit(1);
  }
}

function main() {
  console.log('📡 Fetching config from AWS CloudFormation stack:', STACK_NAME);
  const outputs = getStackOutputs();

  const byKey = {};
  for (const o of outputs) {
    byKey[o.OutputKey] = o.OutputValue;
  }

  let userPoolId = byKey.UserPoolId;
  let userPoolClientId = byKey.UserPoolClientId;
  const apiUrl = byKey.ApiUrl;
  const graphqlApiUrl = byKey.GraphqlApiUrl;

  if (!userPoolId) {
    console.error('\n❌ UserPoolId not found in stack outputs.\n');
    process.exit(1);
  }

  // Fallback: fetch Client ID from Cognito if not in stack (stack deployed before output was added)
  if (!userPoolClientId) {
    try {
      const list = JSON.parse(
        execSync(
          `aws cognito-idp list-user-pool-clients --user-pool-id ${userPoolId} --region ${REGION} --output json`,
          { encoding: 'utf8' }
        )
      );
      const client = list.UserPoolClients?.find(
        (c) => c.ClientName === 'gettrainmate-web-client' || c.ClientName?.includes('web')
      ) || list.UserPoolClients?.[0];
      if (client?.ClientId) userPoolClientId = client.ClientId;
    } catch (e) {
      // ignore; will prompt user to set manually
    }
  }

  const lines = [
    '# Auto-generated by scripts/sync-env-from-aws.js',
    '# Source: CloudFormation stack outputs',
    '',
    '# Cognito (required for login)',
    `VITE_COGNITO_USER_POOL_ID=${userPoolId}`,
    `VITE_COGNITO_CLIENT_ID=${userPoolClientId || 'SET_FROM_COGNITO_CONSOLE'}`,
    `VITE_COGNITO_REGION=${REGION}`,
    '',
    '# API',
    `VITE_API_URL=${apiUrl || 'http://localhost:3001'}`,
  ];

  if (graphqlApiUrl) {
    lines.push('');
    lines.push('# AppSync GraphQL (optional)');
    lines.push(`VITE_APPSYNC_GRAPHQL_URL=${graphqlApiUrl}`);
    lines.push(`VITE_APPSYNC_REGION=${REGION}`);
  }

  const envPath = path.join(ROOT, 'apps', 'web', '.env');
  fs.writeFileSync(envPath, lines.join('\n') + '\n', 'utf8');

  console.log('✅ Wrote', envPath);
  if (!userPoolClientId) {
    console.log('⚠️  UserPoolClientId not in stack. Set VITE_COGNITO_CLIENT_ID manually from AWS Cognito Console.');
  }
}

main();
